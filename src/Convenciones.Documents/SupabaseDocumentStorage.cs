using System.Net;
using System.Text;
using Microsoft.Extensions.Configuration;

namespace Convenciones.Documents;

/// <summary>
/// Stores document bytes in a private Supabase Storage bucket.
/// </summary>
/// <remarks>
/// <para>
/// This is the deployment path. It is selected when <c>Documents:SupabaseUrl</c>,
/// <c>Documents:SupabaseSecretKey</c> and <c>Documents:Bucket</c> are configured; otherwise the API
/// falls back to <see cref="LocalDocumentStorage"/> for local development.
/// </para>
/// <para>
/// The secret key is a server-side credential: it bypasses every storage RLS policy. It is never
/// read from a <c>VITE_</c> variable and never leaves the API container.
/// </para>
/// <para>
/// Object keys are generated by the server and are escaped segment by segment, so a key containing
/// <c>..</c>, a leading slash or a separator cannot address an object outside the bucket.
/// </para>
/// </remarks>
public sealed class SupabaseDocumentStorage : IDocumentStorage
{
    private readonly HttpClient _httpClient;
    private readonly string _bucket;

    public SupabaseDocumentStorage(HttpClient httpClient, IConfiguration configuration)
    {
        ArgumentNullException.ThrowIfNull(httpClient);
        ArgumentNullException.ThrowIfNull(configuration);

        _bucket = configuration["Documents:Bucket"]
            ?? throw new InvalidOperationException("Documents:Bucket is not configured.");

        _httpClient = httpClient;
    }

    internal Uri? BaseAddress => _httpClient.BaseAddress;

    internal HttpClient HttpClient => _httpClient;

    public async Task SaveAsync(string key, Stream content, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);

        using var request = new HttpRequestMessage(HttpMethod.Put, ObjectPath(key))
        {
            Content = new StreamContent(content),
        };
        request.Content.Headers.ContentType = new System.Net.Http.Headers.MediaTypeHeaderValue("application/octet-stream");
        // The document id is unique, so a re-upload is a replacement rather than a second object.
        request.Headers.TryAddWithoutValidation("x-upsert", "true");

        using var response = await _httpClient.SendAsync(request, cancellationToken).ConfigureAwait(false);
        await EnsureSuccessAsync(response, "upload", key, cancellationToken).ConfigureAwait(false);
    }

    public async Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken)
    {
        using var request = new HttpRequestMessage(HttpMethod.Get, ObjectPath(key));
        using var response = await _httpClient.SendAsync(request, cancellationToken).ConfigureAwait(false);

        if (response.StatusCode == HttpStatusCode.NotFound)
        {
            return null;
        }

        await EnsureSuccessAsync(response, "download", key, cancellationToken).ConfigureAwait(false);

        // Buffer the object and release the response: the caller owns a plain stream and a leaked
        // HttpResponseMessage would keep a pooled connection checked out indefinitely.
        var buffer = new MemoryStream();
        await response.Content.CopyToAsync(buffer, cancellationToken).ConfigureAwait(false);
        buffer.Position = 0;
        return buffer;
    }

    public async Task<bool> ExistsAsync(string key, CancellationToken cancellationToken)
    {
        using var request = new HttpRequestMessage(HttpMethod.Get, ObjectPath(key));
        request.Headers.Range = new System.Net.Http.Headers.RangeHeaderValue(0, 0);

        using var response = await _httpClient.SendAsync(request, cancellationToken).ConfigureAwait(false);

        if (response.StatusCode == HttpStatusCode.NotFound)
        {
            return false;
        }

        await EnsureSuccessAsync(response, "probe", key, cancellationToken).ConfigureAwait(false);
        return true;
    }

    public async Task DeleteAsync(string key, CancellationToken cancellationToken)
    {
        using var request = new HttpRequestMessage(HttpMethod.Delete, ObjectPath(key));
        using var response = await _httpClient.SendAsync(request, cancellationToken).ConfigureAwait(false);

        // Deleting an object that is already gone is not a failure: the caller asked for absence.
        if (response.StatusCode == HttpStatusCode.NotFound)
        {
            return;
        }

        await EnsureSuccessAsync(response, "delete", key, cancellationToken).ConfigureAwait(false);
    }

    private string ObjectPath(string key)
    {
        var escaped = string.Join(
            '/',
            key.Split('/', StringSplitOptions.RemoveEmptyEntries).Select(Uri.EscapeDataString));

        return $"object/{Uri.EscapeDataString(_bucket)}/{escaped}";
    }

    private static async Task EnsureSuccessAsync(
        HttpResponseMessage response,
        string operation,
        string key,
        CancellationToken cancellationToken)
    {
        if (response.IsSuccessStatusCode)
        {
            return;
        }

        var detail = await response.Content.ReadAsStringAsync(cancellationToken).ConfigureAwait(false);
        var code = (int)response.StatusCode;

        // The message names the operation and the key, never the bucket credentials.
        throw new HttpRequestException(
            $"Supabase Storage {operation} failed with {code} for '{key}': {Trim(detail)}",
            inner: null,
            statusCode: response.StatusCode);
    }

    private static string Trim(string value) =>
        value.Length <= 300 ? value : value[..300] + "...";
}
